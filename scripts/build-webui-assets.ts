/**
 * Bundles the WebUI browser client and emits it as a TypeScript module of
 * string constants.
 *
 * The outer build runs `bun build --compile --bytecode`. Embedding the client
 * as plain string constants keeps it transparent to that step, instead of
 * relying on HTML-import asset embedding whose behavior under `--bytecode` is
 * unverified here.
 */

import { mkdirSync, writeFileSync } from 'fs'
import { dirname, resolve } from 'path'

const root = resolve(import.meta.dir, '..')
const entrypoint = resolve(root, 'src/webui/client/index.tsx')
const outFile = resolve(root, 'src/webui/generated/assets.ts')

export async function buildWebuiAssets(options: {
  minify: boolean
}): Promise<{ jsBytes: number; cssBytes: number }> {
  const result = await Bun.build({
    entrypoints: [entrypoint],
    target: 'browser',
    format: 'esm',
    minify: options.minify,
    sourcemap: 'none',
    define: {
      'process.env.NODE_ENV': JSON.stringify(
        options.minify ? 'production' : 'development',
      ),
    },
  })

  if (!result.success) {
    for (const log of result.logs) {
      console.error(log)
    }
    throw new Error('WebUI client build failed')
  }

  let js = ''
  let css = ''
  for (const artifact of result.outputs) {
    const text = await artifact.text()
    if (artifact.path.endsWith('.css')) {
      css += text
    } else {
      js += text
    }
  }

  if (!js) {
    throw new Error('WebUI client build produced no JavaScript')
  }

  const module = [
    '// Generated by scripts/build-webui-assets.ts. Do not edit, do not commit.',
    `export const WEBUI_JS = ${JSON.stringify(js)}`,
    `export const WEBUI_CSS = ${JSON.stringify(css)}`,
    `export const WEBUI_JS_HASH = ${JSON.stringify(hash(js))}`,
    `export const WEBUI_CSS_HASH = ${JSON.stringify(hash(css))}`,
    '',
  ].join('\n')

  mkdirSync(dirname(outFile), { recursive: true })
  writeFileSync(outFile, module, 'utf-8')

  return {
    jsBytes: Buffer.byteLength(js),
    cssBytes: Buffer.byteLength(css),
  }
}

function hash(text: string): string {
  return Bun.hash(text).toString(16).padStart(16, '0').slice(0, 12)
}

/**
 * Writes an empty asset module. A WEBUI-off build still has to resolve the
 * import, and a fresh checkout has no generated file, so the stub keeps the
 * main build from depending on whether the client was ever bundled.
 */
export function writeStubWebuiAssets(): void {
  mkdirSync(dirname(outFile), { recursive: true })
  writeFileSync(
    outFile,
    [
      '// Generated stub: built without the WEBUI feature.',
      "export const WEBUI_JS = ''",
      "export const WEBUI_CSS = ''",
      "export const WEBUI_JS_HASH = ''",
      "export const WEBUI_CSS_HASH = ''",
      '',
    ].join('\n'),
    'utf-8',
  )
}

if (import.meta.main) {
  const sizes = await buildWebuiAssets({
    minify: !process.argv.includes('--dev'),
  })
  console.log(
    `WebUI assets: ${sizes.jsBytes} B js, ${sizes.cssBytes} B css → src/webui/generated/assets.ts`,
  )
}
